/* Native language names for the buttons */
const LANG_LABELS = {
  en: 'English',
  fr: 'Français',
  es: 'Español',
  sw: 'Kiswahili',
  ny: 'Chichewa'
};

let currentLang = localStorage.getItem('ghe-lang') || 'en';

function applyTranslations(lang) {
  const t = TRANSLATIONS[lang];
  if (!t) return;
  currentLang = lang;
  localStorage.setItem('ghe-lang', lang);

  /* Text content */
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.textContent = t[key];
  });

  /* HTML content (for items that may include entities) */
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });

  /* Placeholder attributes */
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key] !== undefined) el.setAttribute('placeholder', t[key]);
  });

  /* Update active button */
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.dataset.lang === lang);
  });
}

/* Wire up buttons after DOM is ready */
document.addEventListener('DOMContentLoaded', function () {
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', function () {
      applyTranslations(this.dataset.lang);
    });
  });

  /* Apply saved or default language */
  applyTranslations(currentLang);
});
